import {
  BadRequestException,
  Injectable,
  PayloadTooLargeException,
  ServiceUnavailableException,
} from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { memoryStorage } from 'multer';
import type { MulterOptions } from '@nestjs/platform-express/multer/interfaces/multer-options.interface.js';

export const BLOG_IMAGE_DIRECTORY = resolve(process.cwd(), 'src/asset/images');
export const MAX_BLOG_IMAGE_BYTES = 5 * 1024 * 1024;
export const blogImageUploadOptions: MulterOptions = {
  storage: memoryStorage(),
  limits: {
    fileSize: MAX_BLOG_IMAGE_BYTES,
    files: 1,
    fields: 6,
    parts: 7,
    fieldSize: 400000,
  },
  fileFilter: (_request, file, callback) => {
    if (!['image/jpeg', 'image/png', 'image/webp'].includes(file.mimetype)) {
      return callback(
        new BadRequestException('Image must be JPEG, PNG, or WebP'),
        false,
      );
    }
    callback(null, true);
  },
};

@Injectable()
export class BlogImageStore {
  async save(file: Express.Multer.File): Promise<string> {
    if (!file.buffer?.length) {
      throw new BadRequestException('Image must not be empty');
    }
    if (file.buffer.length > MAX_BLOG_IMAGE_BYTES) {
      throw new PayloadTooLargeException('Image must be at most 5 MB');
    }
    const buffer = file.buffer;
    let extension: string | undefined;
    if (
      file.mimetype === 'image/png' &&
      buffer
        .subarray(0, 8)
        .equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))
    ) {
      extension = 'png';
    }
    if (
      file.mimetype === 'image/jpeg' &&
      buffer[0] === 255 &&
      buffer[1] === 216 &&
      buffer[2] === 255
    ) {
      extension = 'jpg';
    }
    if (
      file.mimetype === 'image/webp' &&
      buffer.toString('ascii', 0, 4) === 'RIFF' &&
      buffer.toString('ascii', 8, 12) === 'WEBP'
    ) {
      extension = 'webp';
    }
    if (!extension) {
      throw new BadRequestException(
        'Image contents do not match a supported image type',
      );
    }
    const filename = `${randomUUID()}.${extension}`;
    const { url, secretKey, bucket } = this.storageConfig();
    try {
      const response = await fetch(
        `${url}/storage/v1/object/${bucket}/${filename}`,
        {
          method: 'POST',
          headers: {
            apikey: secretKey,
            'Content-Type': file.mimetype,
            'x-upsert': 'false',
          },
          body: new Uint8Array(buffer),
          signal: AbortSignal.timeout(30_000),
          redirect: 'error',
        },
      );
      await response.arrayBuffer();
      if (!response.ok) throw new Error('Upload rejected');
    } catch {
      throw new ServiceUnavailableException(
        'Image upload failed. Please try again.',
      );
    }
    return `${url}/storage/v1/object/public/${bucket}/${filename}`;
  }

  async discard(url: string): Promise<void> {
    const { url: projectUrl, secretKey, bucket } = this.storageConfig();
    const prefix = `${projectUrl}/storage/v1/object/public/${bucket}/`;
    if (!url.startsWith(prefix)) return;
    const filename = url.slice(prefix.length);
    // Only delete flat UUID filenames generated by this store, never external URLs or arbitrary paths.
    if (!/^[0-9a-f-]{36}\.(png|jpg|webp)$/.test(filename)) return;
    try {
      const response = await fetch(
        `${projectUrl}/storage/v1/object/${bucket}`,
        {
          method: 'DELETE',
          headers: { apikey: secretKey, 'Content-Type': 'application/json' },
          body: JSON.stringify({ prefixes: [filename] }),
          signal: AbortSignal.timeout(30_000),
          redirect: 'error',
        },
      );
      await response.arrayBuffer();
      if (!response.ok) throw new Error('Deletion rejected');
    } catch {
      throw new ServiceUnavailableException(
        'Unable to remove the unused uploaded image.',
      );
    }
  }

  private storageConfig() {
    const url = process.env.SUPABASE_URL?.trim().replace(/\/+$/, '');
    const secretKey = process.env.SUPABASE_SECRET_KEY?.trim();
    const bucket = process.env.SUPABASE_STORAGE_BUCKET?.trim() || 'blog-images';
    if (
      !url?.startsWith('https://') ||
      !secretKey ||
      !/^[a-zA-Z0-9_-]+$/.test(bucket)
    ) {
      throw new ServiceUnavailableException(
        'Supabase image storage is not configured',
      );
    }
    return { url, secretKey, bucket };
  }
}
